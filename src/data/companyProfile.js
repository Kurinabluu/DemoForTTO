export function getServiceFaqs(serviceName) {
  const key = String(serviceName || '').trim()
  if (SERVICE_FAQS[key]) return SERVICE_FAQS[key]
  if (key.includes('一日游') || key.includes('多日游')) return SERVICE_FAQS['一日游/多日游']
  if (key.includes('热门') || key.includes('门票')) return SERVICE_FAQS['热门项目']
  return []
}
